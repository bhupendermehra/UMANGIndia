<li><strong>ट्यूशन शुल्क प्रतिपूर्ति:</strong> संस्थान द्वारा लिया जाने वाला पूरा ट्यूशन शुल्क, राज्य सरकार द्वारा अधिसूचित दरों के अधीन, प्रतिपूर्ण किया जाता है।</li>
<li><strong>रखरखाव भत्ता:</strong> आपकी श्रेणी और कोर्स के प्रकार (दिवस विद्यार्थी या छात्रावास) के आधार पर रखरखाव भत्ता प्रदान किया जाता है।</li>
<li><strong>DBT के माध्यम से भुगतान:</strong> स्वीकृत राशि सीधे डायरेक्ट बेनिफिट ट्रांसफर के माध्यम से आपके बैंक खाते में जमा की जाती है।</li>
</ul>
<p>ट्यूशन प्रतिपूर्ति और रखरखाव भत्ते की सटीक दरें श्रेणी और कोर्स के प्रकार के अनुसार भिन्न होती हैं। वर्तमान दरों के लिए हमेशा नवीनतम सरकारी अधिसूचना देखें।</p>


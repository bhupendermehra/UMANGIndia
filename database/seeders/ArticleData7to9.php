<li><strong>लाभ जारी:</strong> सत्यापित होने के बाद, लाभ योजना चरण के अनुसार जारी किया जाता है — जन्म पर, स्कूली शिक्षा मील के पत्थर पर, या जैसा कि अधिसूचित है।</li>

<h2>माझी कन्या भाग्यश्री योजना</h2>
<p>माझी कन्या भाग्यश्री योजना महाराष्ट्र के महिला एवं बाल विकास विभाग द्वारा चलाई जाने वाली एक शर्त-आधारित लाभ योजना है। यह उन परिवारों को वित्तीय प्रोत्साहन प्रदान करती है जिनके पास बेटी है, जिससे परिवारों को अपनी बेटियों के स्वास्थ्य, पोषण और शिक्षा में निवेश करने के लिए प्रोत्साहित किया जाता है।</p>

<h3>पात्रता</h3>
<p>यह योजना महाराष्ट्र में उन परिवारों के लिए उपलब्ध है जो निम्नलिखित शर्तों को पूरा करते हैं:</p>
<ul>
<li>परिवार के पास एक बेटी होनी चाहिए जो योजना के तहत अधिसूचित आयु और मानदंडों को पूरा करती हो।</li>
<li>परिवार को राज्य सरकार द्वारा निर्दिष्ट आय और परिवार के आकार के मानदंडों को पूरा करना चाहिए।</li>
<li>यह योजना उन परिवारों का समर्थन करने के लिए डिज़ाइन की गई है जो निर्दिष्ट मानदंडों के तहत बेटी को जन्म देते हैं और उसका पालन करते हैं।</li>
</ul>

<h3>लाभ</h3>
<ul>
<li>पात्र बेटी के लिए शर्त-आधारित वित्तीय लाभ या प्रोत्साहन।</li>
<li>लाभ राशि और संरचना विभाग पोर्टल पर प्रकाशित आधिकारिक योजना मानदंडों का पालन करती है।</li>
<li>भुगतान जन्म पंजीकरण और स्कूली शिक्षा चरणों जैसे मील के पत्थर से जुड़े होते हैं।</li>
</ul>

<h3>आवेदन कैसे करें</h3>
<ol>
<li><strong>बेटी के जन्म का पंजीकरण करें:</strong> सुनिश्चित करें कि जन्म स्थानीय नगरपालिका कार्यालय या आंगनवाड़ी केंद्र के माध्यम से आधिकारिक रूप से पंजीकृत है।</li>
<li><strong>विभाग के माध्यम से आवेदन करें:</strong> अपने स्थानीय आंगनवाड़ी केंद्र या महिला एवं बाल विकास विभाग के कार्यालय से संपर्क करें, या आधिकारिक पोर्टल के माध्यम से आवेदन करें।</li>

<h2>Swasthya Sathi — Detailed Overview</h2>
<p>Swasthya Sathi is a state-level health insurance scheme launched by the Government of West Bengal. It provides health coverage of up to Rs. 5 lakh per family per year, including pre- and post-hospitalisation expenses. The scheme is designed to ensure that every resident family in West Bengal has access to cashless treatment at empanelled hospitals.</p>

<h3>Key Benefits</h3>
<ul>
<li>Health insurance cover of up to Rs. 5 lakh per family per year</li>
<li>Cashless treatment at empanelled hospitals</li>
<li>Covers pre- and post-hospitalisation expenses</li>
<li>Smart card issued to each enrolled family for easy access</li>
</ul>

<h3>Eligibility</h3>
<p>All resident families of West Bengal are covered under the Swasthya Sathi scheme. There is no income-based exclusion — if you are a resident of West Bengal, your family is eligible.</p>

<h3>How to Apply</h3>
<ol>
<li>Families are enrolled through <strong>Duare Sarkar camps</strong>, Gram Panchayats, or Municipalities</li>
<li>A Swasthya Sathi smart card is issued to the family</li>
<li>Visit any empanelled hospital and present the smart card</li>
<li>Treatment is cashless — no upfront payment required</li>
</ol>
<p>For more details, visit the <a href="https://swasthya.sathi.gov.in" target="_blank" rel="noopener">official Swasthya Sathi portal</a>.</p>

<h2>Ayushman Bharat PMJAY — Detailed Overview</h2>
<p>Ayushman Bharat Pradhan Mantri Jan Arogya Yojana (PMJAY) is the world\'s largest government-funded health insurance scheme. It provides Rs. 5 lakh per family per year for secondary and tertiary care hospitalisation, covering over 1,949 medical packages at 29,000+ empanelled hospitals across India.</p>

<h3>Key Benefits</h3>
<ul>
<li>Rs. 5 lakh per family per year health cover</li>
<li>Cashless treatment at 29,000+ empanelled hospitals nationwide</li>
<li>1,949 medical packages covering surgeries, day care procedures, and ICU treatments</li>
<li>Paperless and cashless claims process</li>
</ul>

<h3>Eligibility</h3>
<p>Unlike Swasthya Sathi, Ayushman Bharat eligibility is based on the Socio-Economic Caste Census (SECC) 2011 data. Only families falling under specific rural and urban categories are eligible. You can check your eligibility on the official portal.</p>

<h3>How to Apply</h3>
<ol>
<li>Check your eligibility at <a href="https://mera.pmjay.gov.in" target="_blank" rel="noopener">mera.pmjay.gov.in</a></li>
<li>Get your Ayushman card from the nearest Common Service Centre (CSC)</li>
<li>Carry your Ayushman card to any empanelled hospital in India</li>
<li>Treatment is cashless and paperless</li>
</ol>

<h2>Which Scheme Is Right for You?</h2>
<p>The choice between Swasthya Sathi and Ayushman Bharat depends on your situation:</p>

<h3>Choose Swasthya Sathi if:</h3>
<ul>
<li>You are a <strong>resident of West Bengal</strong> — the scheme covers all resident families without income restrictions</li>
<li>You want <strong>guaranteed coverage</strong> regardless of economic category</li>
<li>You prefer <strong>enrolment through local government camps</strong> — no need to visit a separate portal</li>
<li>Your healthcare needs are primarily within West Bengal</li>
</ul>

<h3>Choose Ayushman Bharat PMJAY if:</h3>
<ul>
<li>You live <strong>outside West Bengal</strong> — Ayushman Bharat is available across India</li>
<li>You fall under an <strong>eligible SECC category</strong> — check your status online first</li>
<li>You need <strong>portable coverage</strong> — treatment at any empanelled hospital in any state</li>
<li>You want access to a <strong>larger hospital network</strong> with 29,000+ facilities nationwide</li>
</ul>

<h3>Can You Have Both?</h3>
<p>In some cases, families may be eligible for both schemes. If you live in West Bengal and also qualify under SECC 2011 criteria, you can hold both the Swasthya Sathi smart card and the Ayushman card. However, you cannot claim the same treatment under both schemes simultaneously. Having both gives you the flexibility to use whichever is more convenient for a particular hospital visit.</p>


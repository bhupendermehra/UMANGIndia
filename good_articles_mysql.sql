<p>पीएम-जय पात्रता सख्ती से SECC 2011 के डेटा पर आधारित है। यदि आपका परिवार डेटाबेस में नहीं दिखता है, तो आप इस योजना के तहत पात्र नहीं हैं। हालांकि, कुछ राज्यों की अपनी स्वास्थ्य बीमा योजनाएं हैं जो आपको कवर कर सकती हैं।</p>

<h3>यदि मेरा आयुष्मान कार्ड खो जाता है तो क्या होगा?</h3>
<p>आप अपने आधार कार्ड लेकर किसी भी CSC या अनुबंधित अस्पताल में जाकर डुप्लीकेट कार्ड बनवा सकते हैं। पुनर्जारी के लिए कोई शुल्क नहीं है।</p>


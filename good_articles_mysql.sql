<h2>Apply for West Bengal Welfare Schemes Today</h2>
<p>These three schemes represent real, actionable support for women and children in West Bengal. Whether you need a scholarship to continue studying, a bicycle to reach school, or financial help as an SC/ST student, there is a programme designed for you. Start by checking your eligibility on the respective <a href="/scheme/kanyashree-prakalpa-wb">Kanyashree</a>, <a href="/scheme/sabooj-sathi-wb">Sabooj Sathi</a>, and <a href="/scheme/sikshashree-wb">Sikshashree</a> scheme pages on UmangIndia.</p>','<p>पश्चिम बंगाल महिला और बाल कल्याण की कुछ भारत की सबसे प्रभावी योजनाएं चलाता है। लड़कियों को स्कूल में रखने वाली छात्रवृत्ति से लेकर ड्रॉपआउट दर कम करने वाली साइकिल तक, ये कार्यक्रम जमीनी स्तर पर वास्तविक अंतर ला रहे हैं। यह लेख 2026 में आवेदन की जा सकने वाली तीन प्रमुख योजनाओं — कन्याश्री प्रकल्प, सबुज साथी और शिक्षाश्री — का परिचय देता है और आपको समझने में मदद करता है कि कौन सी आपकी आवश्यकताओं के अनुरूप है।</p>

<h2>ये योजनाएं क्यों महत्वपूर्ण हैं</h2>
<p>आधिकारिक आंकड़ों के अनुसार, पश्चिम बंगाल ने लगातार महिलाओं और बच्चों के शिक्षा-संबंधी कल्याण में निवेश किया है। यहां कवर की गई तीन योजनाएं विभिन्न समूहों को लक्षित करती हैं — स्कूल में लड़कियां, परिवहन सहायता की आवश्यकता वाले छात्र, और अनुसूचित जाति/अनुसूचित जनजाति के दिवस-छात्र — लेकिन इनका एक साझा लक्ष्य है: युवाओं को शिक्षा में बनाए रखना और परिवारों के लिए वित्तीय बाधाओं को कम करना।</p>

<h2>1. कन्याश्री प्रकल्प — लड़कियों के लिए वार्षिक छात्रवृत्ति</h2>
<p>कन्याश्री प्रकल्प पश्चिम बंगाल की छात्राओं के लिए प्रमुख छात्रवृत्ति कार्यक्रम है। यह योजना यह सुनिश्चित करने के लिए दो प्रकार की वित्तीय सहायता प्रदान करती है कि आर्थिक तंगी परिवारों को अपनी बेटियों को स्कूल से निकालने पर मजबूर न करे।</p>

<h3>लाभ</h3>
<ul>
<li><strong>वार्षिक छात्रवृत्ति 1,000 रुपये</strong> — कक्षा VIII या उससे ऊपर पढ़ने वाली पात्र लड़कियों को हर साल भुगतान</li>
<li><strong>एकमुश्त अनुदान 25,000 रुपये</strong> — लड़की के 18 वर्ष की आयु पर भुगतान, बशर्ते अविवाहित हो और पात्रता मानदंड पूरे करती हो</li>
</ul>
<p>दोनों भुगतान सीधे लाभार्थी के बैंक खाते में स्थानांतरित किए जाते हैं।</p>

<h3>पात्रता</h3>
<ul>
<li>पश्चिम बंगाल की अविवाहित छात्राएं</li>
<li>13 से 18 वर्ष की आयु (विशेष आवश्यकताओं वाली लड़कियों के लिए 19 वर्ष तक)</li>
<li>किसी मान्यता प्राप्त संस्थान में कक्षा VIII या उससे ऊपर पढ़ रही हों</li>
</ul>

<h3>आवेदन कैसे करें</h3>
<p>कन्याश्री आवेदन आम तौर पर स्कूलों और शैक्षणिक संस्थानों के माध्यम से प्रक्रियाधीन होते हैं। छात्राएं आधिकारिक पोर्टल के माध्यम से ऑनलाइन भी आवेदन कर सकती हैं। नवीनतम आवेदन विवरण के लिए अपने स्कूल प्रशासन से संपर्क करें या <a href="https://banglarshiksha.wb.gov.in" target="_blank" rel="noopener">banglarshiksha.wb.gov.in</a> पर जाएं।</p>

<p><strong>अधिक जानें:</strong> पूर्ण विवरण और आधिकारिक लिंक के लिए UmangIndia पर <a href="/scheme/kanyashree-prakalpa-wb">कन्याश्री प्रकल्प योजना पृष्ठ</a> पर जाएं।</p>

<h2>2. सबुज साथी — छात्रों के लिए मुफ्त साइकिल</h2>
<p>सबुज साथी एक अनूठी पहल है जो पश्चिम बंगाल में सरकारी और सरकार-सहायता प्राप्त स्कूलों के छात्रों को मुफ्त साइकिल प्रदान करती है। यह योजना सीधे स्कूल उपस्थिति की सबसे बड़ी बाधाओं में से एक को संबोधित करती है: दूरी।</p>

<h3>लाभ</h3>
<ul>
<li>प्रत्येक पात्र छात्र को स्कूल जाने-आने के लिए एक <strong>मुफ्त साइकिल</strong></li>
<li>यात्रा का समय कम करता है और विशेषकर ग्रामीण क्षेत्रों में शिक्षा तक पहुंच में सुधार करता है</li>
<li>उन छात्रों के बीच ड्रॉपआउट दर को कम करने में मदद करता है जो अपने स्कूल से दूर रहते हैं</li>
</ul>

<h3>पात्रता</h3>
<ul>
<li>पश्चिम बंगाल में सरकारी या सरकार-सहायता प्राप्त स्कूलों में पढ़ने वाले छात्र</li>
<li>आम तौर पर कक्षा IX और उससे ऊपर से लागू</li>
<li>यह योजना लड़कों और लड़कियों दोनों के लिए खुली है</li>
</ul>

<h3>आवेदन कैसे करें</h3>
<p>वितरण आम तौर पर स्कूलों के माध्यम से आयोजित किए जाते हैं। स्कूल प्रशासन पात्र छात्रों की पहचान करता है और साइकिल वितरण का समन्वय करता है। वितरण के नवीनतम चक्र के लिए, अपने स्कूल से जांच करें या <a href="https://paschimbangatourism.gov.in" target="_blank" rel="noopener">पश्चिम बंगाल सरकार पोर्टल</a> पर जाएं।</p>

<p><strong>अधिक जानें:</strong> अद्यतन जानकारी के लिए UmangIndia पर <a href="/scheme/sabooj-sathi-wb">सबुज साथी योजना पृष्ठ</a> पर जाएं।</p>

<h2>3. शिक्षाश्री — अनुसूचित जाति/अनुसूचित जनजाति के छात्रों के लिए छात्रवृत्ति</h2>
<p>शिक्षाश्री पश्चिम बंगाल में अनुसूचित जाति (SC) और अनुसूचित जनजाति (ST) के दिवस-छात्रों के लिए विशेष रूप से डिज़ाइन की गई छात्रवृत्ति योजना है। यह हाशिए के समुदायों के छात्रों के बीच शिक्षा जारी रखने के लिए वार्षिक वित्तीय सहायता प्रदान करती है।</p>

<h3>लाभ</h3>
<ul>
<li>पात्र SC/ST दिवस-छात्रों के लिए <strong>प्रति वर्ष 800 रुपये</strong></li>
<li>सरकारी या सरकार-सहायता प्राप्त स्कूलों में कक्षा V से VIII तक पढ़ने वाले छात्रों को कवर करता है</li>
</ul>

<h3>पात्रता</h3>
<ul>
<li>पश्चिम बंगाल में अधिसूचित SC/ST समुदायों से संबंधित छात्र</li>
<li>सरकारी या सरकार-सहायता प्राप्त स्कूलों में कक्षा V से VIII में पढ़ रहे हों</li>
<li>वार्षिक परिवार की आय 2.5 लाख रुपये से अधिक न हो</li>
<li>दिवस-छात्र हों (छात्रावास नहीं)</li>
</ul>

<h3>आवेदन कैसे करें</h3>
<p>आवेदन स्कूलों और राज्य शिक्षा विभाग के माध्यम से प्रसंस्करण होते हैं। छात्रों को वर्तमान आवेदन चक्र और आवश्यक दस्तावेजों के लिए अपने स्कूल प्रशासन से संपर्क करना चाहिए।</p>


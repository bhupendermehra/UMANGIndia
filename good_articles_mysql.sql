<h3>Step 3: Upload Eligibility Documents</h3>
<p>Upload your income certificate, BPL card, Aadhaar card, and bank account details. Make sure all documents are clear and valid.</p>

<h3>Step 4: Submit and Wait for Verification</h3>
<p>After submitting your application, the department will verify your eligibility. Once verified, the benefits will be applied to your account. You can track your application status on the same portal.</p>


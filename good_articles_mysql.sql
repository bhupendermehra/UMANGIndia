<h2>What Is PM-KISAN?</h2>
<p>PM-KISAN is a central sector scheme launched on 24 February 2019. Under this scheme, eligible farmer families receive Rs. 6,000 per year. The amount is paid in three equal installments of Rs. 2,000 each. The money is sent directly to the farmer\'s bank account through Direct Benefit Transfer (DBT).</p>
<p>Since its launch, the scheme has transferred over Rs. 2 lakh crore to more than 11 crore farmer families. It is one of the largest direct cash transfer programs in the world.</p>

<h2>Who Is Eligible for PM-KISAN?</h2>
<p>All landholding farmer families with cultivable land are eligible for this scheme. However, certain categories of people are excluded:</p>
<ul>
<li>Institutional landholders</li>
<li>Former or current holders of constitutional posts</li>
<li>Former or current ministers</li>
<li>Serving or retired officers and employees of Central or State governments</li>
<li>PSU employees and government employees</li>
<li>Income taxpayers</li>
<li>Professionals with higher income such as doctors, engineers, and lawyers</li>
</ul>
<p>If your family owns cultivable land and you do not fall into any of these excluded categories, you can apply for PM-KISAN.</p>

<h2>Documents Required for PM-KISAN Registration</h2>

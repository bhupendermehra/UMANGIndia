<h2>1. Kanyashree Prakalpa — Annual Scholarship for Girls</h2>
<p>Kanyashree Prakalpa is West Bengal\'s flagship scholarship programme for girl students. It provides two types of financial support to ensure that economic hardship does not force families to pull their daughters out of school.</p>

<h3>Benefits</h3>
<ul>
<li><strong>Annual scholarship of Rs. 1,000</strong> — paid every year to eligible girls studying in class VIII or above</li>
<li><strong>One-time grant of Rs. 25,000</strong> — paid when the girl turns 18, provided she is unmarried and meets the eligibility criteria</li>
</ul>
<p>Both payments are transferred directly to the beneficiary\'s bank account.</p>

<h3>Eligibility</h3>
<ul>
<li>Unmarried girl students of West Bengal</li>
<li>Aged 13 to 18 years (up to 19 years for girls with special needs)</li>
<li>Must be studying in class VIII or above in a recognized institution</li>
</ul>

<h3>How to Apply</h3>
<p>Kanyashree applications are typically routed through schools and educational institutions. Students can also apply online via the official portal. Contact your school administration or visit <a href="https://banglarshiksha.wb.gov.in" target="_blank" rel="noopener">banglarshiksha.wb.gov.in</a> for the latest application details.</p>

<p><strong>Learn more:</strong> Visit the <a href="/scheme/kanyashree-prakalpa-wb">Kanyashree Prakalpa scheme page</a> on UmangIndia for full details and the official link.</p>

<h2>2. Sabooj Sathi — Free Bicycles for Students</h2>
<p>Sabooj Sathi is a unique initiative that provides free bicycles to students in government and government-aided schools across West Bengal. The scheme directly addresses one of the biggest barriers to school attendance: distance.</p>

<h3>Benefits</h3>
<ul>
<li>A <strong>free bicycle</strong> to each eligible student to commute to and from school</li>
<li>Reduces travel time and improves access to education, especially in rural areas</li>
<li>Helps reduce dropout rates among students who live far from their school</li>
</ul>

<h3>Eligibility</h3>
<ul>
<li>Students studying in government or government-aided schools in West Bengal</li>
<li>Generally applicable from class IX and above</li>
<li>The scheme is open to both boys and girls</li>
</ul>

<h3>How to Apply</h3>
<p>Distributions are usually organised through schools. The school administration identifies eligible students and coordinates bicycle distribution. For the latest cycle of distributions, check with your school or visit the <a href="https://paschimbangatourism.gov.in" target="_blank" rel="noopener">West Bengal government portal</a>.</p>

<p><strong>Learn more:</strong> Visit the <a href="/scheme/sabooj-sathi-wb">Sabooj Sathi scheme page</a> on UmangIndia for updated information.</p>

<h2>3. Sikshashree — Scholarship for SC/ST Students</h2>
<p>Sikshashree is a scholarship programme designed specifically for Scheduled Caste (SC) and Scheduled Tribe (ST) day-scholars in West Bengal. It provides annual financial support to encourage continued education among students from marginalised communities.</p>

<h3>Benefits</h3>
<ul>
<li><strong>Rs. 800 per year</strong> for eligible SC/ST day-scholars</li>
<li>Covers students studying in classes V to VIII in government or government-aided schools</li>
</ul>

<h3>Eligibility</h3>
<ul>
<li>Students belonging to notified SC/ST communities in West Bengal</li>
<li>Studying in classes V to VIII in government or government-aided schools</li>
<li>Annual family income must not exceed Rs. 2.5 lakh</li>
<li>Must be a day-scholar (not a hosteller)</li>
</ul>

<h3>How to Apply</h3>
<p>Applications are processed through schools and the state education department. Students should contact their school administration for the current application cycle and required documents.</p>

<p><strong>Learn more:</strong> Visit the <a href="/scheme/sikshashree-wb">Sikshashree scheme page</a> on UmangIndia for complete eligibility details.</p>


<li><strong>Aadhaar Card</strong> — This is mandatory for identity verification and linking with your bank account.</li>
<li><strong>Bank Account Details</strong> — Your savings account number and IFSC code. The installment will be credited to this account.</li>
<li><strong>Land Records</strong> — Your Khata number and Khasra number as mentioned in your land documents.</li>

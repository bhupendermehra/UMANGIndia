<h3>क्या मैं कार्ड किसी भी राज्य में इस्तेमाल कर सकता हूं?</h3>
<p>हां, आयुष्मान भारत एक राष्ट्रीय योजना है। आप पूरे भारत में किसी भी राज्य में किसी भी अनुबंधित अस्पताल में अपना कार्ड इस्तेमाल कर सकते हैं।</p>


<h2>आयुष्मान भारत पीएम-जय के लिए आवश्यक दस्तावेज</h2>
<p>अधिकतम कवरेज सुनिश्चित करने के लिए दस्तावेज आवश्यकताएं सरल रखी गई हैं। यहां पूरी जांच सूची दी गई है:</p>

<h3>प्राथमिक दस्तावेज (कोई एक)</h3>
<p>अपनी पहचान और पात्रता साबित करने के लिए निम्नलिखित में से कम से कम एक चाहिए:</p>
<ol>
<li><strong>राशन कार्ड</strong> — यह सबसे अधिक इस्तेमाल होने वाला दस्तावेज है। आपका परिवार का नाम राशन कार्ड पर दिखना चाहिए।</li>
<li><strong>आधार कार्ड</strong> — SECC डेटा सत्यापन के साथ पहचान प्रमाण के रूप में इस्तेमाल किया जा सकता है।</li>
<li><strong>कोई भी सरकारी फोटो पहचान</strong> — वोटर आईडी, ड्राइविंग लाइसेंस या पैन कार्ड को पूरक पहचान प्रमाण के रूप में इस्तेमाल किया जा सकता है।</li>
</ol>

<h3>सत्यापन के लिए</h3>
<ul>
<li><strong>SECC डेटा संदर्भ संख्या</strong> — यदि उपलब्ध है, तो यह SECC डेटाबेस में आपके परिवार की पात्रता के त्वरित सत्यापन में मदद करता है।</li>
<li><strong>मोबाइल नंबर</strong> — कार्ड जनरेशन के दौरान OTP सत्यापन के लिए आधार से जुड़ा हुआ।</li>
</ul>


<li>You must be a resident of Madhya Pradesh.</li>
<li>You must belong to a BPL (Below Poverty Line) family or meet the income and residence criteria prescribed by the state government.</li>
<li>You must be working in the unorganised sector — this includes daily-wage labourers, street vendors, domestic workers, rickshaw pullers, auto drivers, and similar occupations.</li>
<li>You must be registered on the official Sambal Yojana portal.</li>
</ul>


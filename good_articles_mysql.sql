<h3>Rural Eligibility (7 Crore Families)</h3>
<ul>
<li>Families with no land and dependent on manual labour</li>
<li>Families with no male member aged 16 to 59 years</li>
<li>Families with a disabled member and no able-bodied adult member</li>
<li>SC/ST households</li>
<li>Bonded labourers</li>
<li>Primitive tribal groups</li>
<li>Manually scavenger families</li>
</ul>

<h3>Urban Eligibility</h3>
<ul>
<li>Ragpickers</li>
<li>Beggars</li>
<li>Domestic workers</li>
<li>Street vendors</li>
<li>Construction workers</li>
<li>Shop workers and helpers</li>
<li>Transport drivers and conductors</li>
<li>Waiters, peons, and other service sector workers</li>
<li>Artisans and hawkers</li>
</ul>
<p>If your family appears in the SECC 2011 database and meets these criteria, you are eligible for PM-JAY benefits.</p>

<h2>Documents Required for Ayushman Bharat PM-JAY</h2>
<p>The document requirements are kept simple to ensure maximum coverage. Here is the complete checklist:</p>

<h3>Primary Documents (Any One)</h3>
<p>You need at least one of the following to prove your identity and eligibility:</p>
<ol>
<li><strong>Ration Card</strong> — This is the most commonly used document. Your family name should appear on the ration card.</li>
<li><strong>Aadhaar Card</strong> — Can be used as an identity proof along with SECC data verification.</li>
<li><strong>Any Government-issued Photo ID</strong> — Voter ID, driving license, or PAN card can be used as supplementary identity proof.</li>
</ol>

<h3>For Verification</h3>
<ul>
<li><strong>SECC Data Reference Number</strong> — If available, this helps in quick verification of your family\'s eligibility in the SECC database.</li>
<li><strong>Mobile Number</strong> — Linked to Aadhaar for OTP verification during card generation.</li>
</ul>

<h2>How to Check Your Eligibility Online</h2>
<p>Before visiting a hospital or service centre, check your eligibility online:</p>
<ol>
<li>Visit <strong>mera.pmjay.gov.in</strong></li>
<li>Enter your Aadhaar number or ration card number</li>
<li>The system will check whether your family is listed in the SECC database</li>
<li>If eligible, you will see your family members\' names and Ayushman card status</li>
</ol>
<p>You can also call the PM-JAY helpline at <strong>14555</strong> or <strong>1800-111-565</strong> to check eligibility over the phone.</p>

<h2>How to Get Your Ayushman Card</h2>
<p>Once your eligibility is confirmed, here is how you can get your Ayushman card:</p>

<h3>Option 1: Common Service Centre (CSC)</h3>
<ol>
<li>Visit your nearest Common Service Centre (CSC)</li>
<li>Carry your Aadhaar card and ration card</li>
<li>The CSC operator will perform eKYC using your Aadhaar</li>
<li>Your Ayushman card will be generated and printed</li>
<li>A small service charge of Rs. 5 to Rs. 10 may apply</li>
</ol>

<h3>Option 2: Empanelled Hospital</h3>
<ol>
<li>Visit any empanelled hospital under PM-JAY</li>
<li>Go to the Ayushman Bharat help desk or reception</li>
<li>Carry your Aadhaar card or ration card</li>
<li>The hospital will verify your eligibility and generate your card</li>
<li>You can get treatment and the card generated in the same visit</li>
</ol>

<h3>Option 3: Ayushman Arogya Mandir</h3>
<p>You can also visit an Ayushman Arogya Mandir (Health and Wellness Centre) in your area. These centres are equipped to generate Ayushman cards and provide basic health services.</p>

<h2>How to Use Your Ayushman Card for Treatment</h2>
<p>Once you have your Ayushman card, using it for treatment is straightforward:</p>
<ol>
<li>Visit any empanelled hospital — you can find the list at <strong>hospitals.pmjay.gov.in</strong></li>
<li>Go to the Ayushman Bharat help desk at the hospital</li>
<li>Show your Ayushman card and Aadhaar card</li>
<li>The hospital will verify your identity and treatment eligibility</li>
<li>Treatment is cashless — you do not need to pay anything upfront</li>
</ol>
<p>The scheme covers pre-hospitalization, hospitalization, and post-hospitalization expenses. There is no restriction on family size, age, or gender.</p>

<h2>Frequently Asked Questions</h2>

<h3>Can I apply if my name is not in SECC 2011 data?</h3>
<p>PM-JAY eligibility is strictly based on SECC 2011 data. If your family does not appear in the database, you are not eligible under this scheme. However, some states have their own health insurance schemes that may cover you.</p>

<h3>What if my Ayushman card is lost?</h3>
<p>You can get a duplicate card generated by visiting any CSC or empanelled hospital with your Aadhaar card. There is no charge for reissuance.</p>

<h3>Is there a time limit for treatment?</h3>
<p>There is no time limit. You can avail treatment at any empanelled hospital at any time during the year, as long as the treatment falls under the 1,949 approved packages.</p>

<h3>Can I use the card in any state?</h3>
<p>Yes, Ayushman Bharat is a national scheme. You can use your card at any empanelled hospital in any state across India.</p>

<h2>Important Tips</h2>
<ul>
<li>Check your eligibility at mera.pmjay.gov.in before visiting a hospital to avoid disappointment.</li>
<li>Always carry both your Ayushman card and Aadhaar card when visiting an empanelled hospital.</li>
<li>Keep your mobile number updated for any communications related to the scheme.</li>
<li>If you face any issues, call the helpline at 14555 (in Hindi and English).</li>
<li>The scheme covers treatment at both government and private empanelled hospitals — you are not limited to government hospitals.</li>
</ul>

